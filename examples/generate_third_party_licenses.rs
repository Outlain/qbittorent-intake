//! Collect notices for every locked registry package, including platform and
//! test dependencies. Run `cargo fetch --locked` first if the cache is incomplete.
//! This maintenance tool is never part of a runtime image.
use anyhow::{bail, ensure, Context, Result};
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
    process::Command,
};
use walkdir::WalkDir;

fn notice_path(path: &Path) -> bool {
    let name = path
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .to_ascii_lowercase();
    ["license", "licence", "copying", "notice", "copyright"]
        .iter()
        .any(|prefix| name.starts_with(prefix))
        || path.ancestors().skip(1).any(|parent| {
            matches!(
                parent.file_name().and_then(|p| p.to_str()),
                Some("LICENSES" | "licenses")
            )
        })
}

fn text_file(path: &Path) -> Result<String> {
    let text = fs::read_to_string(path).context("Notice must be readable UTF-8 text")?;
    ensure!(!text.trim().is_empty(), "Notice is empty");
    Ok(text)
}

fn package_notices(package: &Value, packages: &[Value]) -> Result<Vec<(String, String)>> {
    let name = package["name"].as_str().context("Missing package name")?;
    let version = package["version"]
        .as_str()
        .context("Missing package version")?;
    let root = Path::new(
        package["manifest_path"]
            .as_str()
            .context("Missing manifest")?,
    )
    .parent()
    .context("Missing package directory")?;
    let mut paths = BTreeMap::<PathBuf, String>::new();
    for entry in WalkDir::new(root).follow_links(false) {
        let entry = entry?;
        let relative = entry.path().strip_prefix(root)?;
        if entry.file_type().is_file() && notice_path(relative) {
            paths.insert(
                entry.path().to_owned(),
                relative.to_string_lossy().replace('\\', "/"),
            );
        }
    }
    if let Some(named) = package["license_file"].as_str() {
        let path = root.join(named).canonicalize()?;
        ensure!(
            path.starts_with(root.canonicalize()?),
            "Declared notice escapes package"
        );
        paths.insert(path, named.to_string());
    }
    if name == "r-efi" {
        paths.insert(
            root.join("AUTHORS"),
            "AUTHORS (license grants and copyrights)".into(),
        );
    }
    let mut notices = paths
        .into_iter()
        .map(|(path, label)| Ok((label, text_file(&path)?)))
        .collect::<Result<Vec<_>>>()?;
    if notices.is_empty() {
        match (name, version) {
            ("valuable", "0.1.1") => notices.push((
                "upstream LICENSE at commit 9efc29b6e58cef28f6566a47aa7e142a55fead77; see examples/support/licenses/README.md".into(),
                include_str!("support/licenses/valuable-0.1.1-LICENSE").to_string(),
            )),
            ("winapi-i686-pc-windows-gnu" | "winapi-x86_64-pc-windows-gnu", "0.4.0") => {
                let parent = packages.iter().find(|p| p["name"] == "winapi" && p["version"] == "0.3.9").context("Expected parent winapi 0.3.9 notices")?;
                let directory = Path::new(parent["manifest_path"].as_str().unwrap()).parent().unwrap();
                for file in ["LICENSE-MIT", "LICENSE-APACHE"] {
                    notices.push((format!("parent winapi 0.3.9/{file}; see examples/support/licenses/README.md"), text_file(&directory.join(file))?));
                }
            }
            _ => bail!("No notice files for {name} {version}; review the upstream license before updating the bundle"),
        }
    }
    notices.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(notices)
}

fn main() -> Result<()> {
    let check = std::env::args()
        .skip(1)
        .any(|argument| argument == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let metadata = Command::new(cargo)
        .current_dir(root)
        .args(["metadata", "--format-version", "1", "--locked", "--offline"])
        .output()?;
    ensure!(
        metadata.status.success(),
        "Offline Cargo metadata failed; run cargo fetch --locked first"
    );
    let metadata: Value = serde_json::from_slice(&metadata.stdout)?;
    let mut packages = metadata["packages"]
        .as_array()
        .context("Missing metadata packages")?
        .iter()
        .filter(|p| !p["source"].is_null())
        .cloned()
        .collect::<Vec<_>>();
    packages.sort_by_key(|p| {
        (
            p["name"].as_str().unwrap().to_string(),
            p["version"].as_str().unwrap().to_string(),
        )
    });
    let mut output = String::from("THIRD-PARTY RUST DEPENDENCY NOTICES\n\nGenerated by: cargo run --example generate_third_party_licenses\nThe inventory includes every registry package in Cargo.lock, including build,\ntest and platform-specific dependencies that may not occur in a Linux image.\nRepeated identical notice texts are included once and referenced by number.\nDeclared license expressions are upstream metadata; inclusion of alternatives\nis not a change to their terms. Cargo package sources are available at the URLs\nbelow. Container OS packages retain their notices in /usr/share/doc.\nRust toolchain notices are bundled separately in runtime images.\n\n");
    output.push_str(&format!(
        "Lockfile SHA-256: {:x}\n\n",
        Sha256::digest(fs::read(root.join("Cargo.lock"))?)
    ));
    let mut texts = Vec::<String>::new();
    let mut ids = BTreeMap::<String, usize>::new();
    for package in &packages {
        let name = package["name"].as_str().unwrap();
        let version = package["version"].as_str().unwrap();
        ensure!(
            package["source"].as_str().unwrap().starts_with("registry+"),
            "Review non-registry dependency {name} before publishing"
        );
        let license = package["license"]
            .as_str()
            .unwrap_or("See supplied notice files");
        output.push_str(&format!("PACKAGE: {name} {version}\nDeclared license: {license}\nSource: https://crates.io/crates/{name}/{version}\n"));
        for (label, text) in package_notices(package, &packages)? {
            let id = match ids.get(&text) {
                Some(id) => *id,
                None => {
                    let id = texts.len() + 1;
                    texts.push(text.clone());
                    ids.insert(text, id);
                    id
                }
            };
            output.push_str(&format!("  Notice {id:03}: {label}\n"));
        }
        output.push('\n');
    }
    for (index, text) in texts.iter().enumerate() {
        output.push_str(&format!(
            "==================== NOTICE {:03} ====================\n",
            index + 1
        ));
        output.push_str(text);
        if !text.ends_with('\n') {
            output.push('\n');
        }
        output.push('\n');
    }
    let target = root.join("THIRD_PARTY_LICENSES.txt");
    if check {
        ensure!(
            fs::read_to_string(target)? == output,
            "Dependency notices are stale; regenerate the bundle"
        );
    } else {
        fs::write(target, &output)?;
    }
    println!(
        "{} packages, {} distinct notice texts, {} bytes",
        packages.len(),
        texts.len(),
        output.len()
    );
    Ok(())
}
